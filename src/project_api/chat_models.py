from pydantic import BaseModel, ConfigDict, Field, field_validator

MAX_MESSAGE_LENGTH = 2000


class ChatRequest(BaseModel):
    """The prompt submitted to the chat endpoint."""

    model_config = ConfigDict(str_strip_whitespace=True)

    message: str = Field(
        min_length=1,
        max_length=MAX_MESSAGE_LENGTH,
        description="Prompt to send to the language model (1–2,000 characters).",
        examples=["Explain dependency injection in simple words."],
    )

    @field_validator("message")
    @classmethod
    def reject_whitespace_only(cls, value: str) -> str:
        if not value:
            raise ValueError("Message must not be empty or whitespace only.")
        return value


class TokenUsage(BaseModel):
    """Token counts returned by the LLM provider, when available."""

    input_tokens: int | None = Field(description="Tokens sent to the model, or null if unavailable.")
    output_tokens: int | None = Field(description="Tokens generated by the model, or null if unavailable.")


class ChatResponse(BaseModel):
    """A generated answer and its model/usage metadata."""

    answer: str = Field(min_length=1)
    model: str
    usage: TokenUsage
